UNCONSTRAINED = None  # value meaning "not limited in this illustrative calculation" (runtime_limit_min only)


@dataclass(frozen=True)
class Input:
    key: str
    label: str
    unit: str
    time_basis: str
    provenance: Provenance
    source: str
    conservative: float | None
    base: float | None
    optimistic: float | None
    capacity_direction: Direction
    integer: bool = False
    notes: str = ""

    def value(self, assumption: Assumption) -> float | None:
        return {"conservative": self.conservative, "base": self.base, "optimistic": self.optimistic}[
            assumption
        ]


