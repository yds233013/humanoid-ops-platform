"""Slice 6 input registry (frozen contract docs/06_scaling_capacity_contract.md section 2, rev 4 at e9c5483).

The ONE place every model input is defined: key, unit, time basis, provenance, source, the three scenario values
and how the input moves capacity. Everything is SYNTHETIC. `unknown_company_data` values are illustrative
placeholders, never claims about a real robot, price or market; outputs that depend on them must say so.
Pure Python: no Django imports (the model and the workbook generator use this module directly).
"""

