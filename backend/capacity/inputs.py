BY_KEY: dict[str, Input] = {i.key: i for i in REGISTRY}


def values(assumption: Assumption) -> dict[str, float | None]:
    """The registry values for one assumption set (platform baseline overrides are applied by the caller)."""
    return {i.key: i.value(assumption) for i in REGISTRY}


def unknown_keys() -> tuple[str, ...]:
    return tuple(i.key for i in REGISTRY if i.provenance == UC)
